import { test, expect } from '@playwright/test'

test('保存日期错误明确指出字段，改正后保留内容并保存', async ({ page }) => {
  await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '新建公司台账' })).toBeVisible()
  await page.request.post('/api/ledgers', { data: { name: '校验提示测试' } })
  await page.reload()
  await page.getByRole('button', { name: '进入校验提示测试' }).click()
  await page.getByRole('button', { name: '上传与录入' }).click()
  await page.getByLabel('物料名称、型号', { exact: true }).fill('日期错误测试物料')
  await page.getByLabel('生产日期', { exact: true }).fill('2026.02.30')
  await page.getByRole('button', { name: '保存记录', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('生产日期第1项')
  await expect(page.getByRole('alert')).toContainText('请填写有效日期')
  await expect(page.getByRole('alert')).toContainText('修改后重新保存')
  await expect(page.getByRole('alert')).toBeInViewport()
  await expect(page.getByLabel('物料名称、型号', { exact: true })).toHaveValue('日期错误测试物料')
  await page.getByLabel('生产日期', { exact: true }).fill('2026.02.28')
  await page.getByRole('button', { name: '保存记录', exact: true }).click()
  await expect(page.getByRole('table')).toContainText('日期错误测试物料')
  await expect(page.getByRole('alert')).toHaveCount(0)
})
