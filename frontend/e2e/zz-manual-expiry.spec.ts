import { expect, test } from '@playwright/test'

test('手动录入生产日期和期限自动计算到期日，修改期限后重新计算', async ({ page }) => {
  if ((await (await page.request.get('/api/setup')).json()).required) await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出', exact: true })).toBeVisible()
  const ledger = await (await page.request.post('/api/ledgers', { data: { name: `手填到期日${Date.now()}` } })).json()
  await page.reload()
  await page.getByRole('button', { name: `进入${ledger.name}`, exact: true }).click()
  await page.getByRole('button', { name: '上传与录入', exact: true }).click()
  const production = page.getByLabel('生产日期', { exact: true })
  const duration = page.getByLabel('保质期', { exact: true })
  const expiry = page.getByLabel('保质期至', { exact: true })
  await production.fill('2026.01.14')
  await duration.fill('12个月')
  await expect(expiry).toHaveValue('2027-01-13')
  await expiry.fill('2027-01-10')
  await duration.fill('24个月')
  await expect(expiry).toHaveValue('2028-01-13')
  await production.fill('2026.02.14')
  await expect(expiry).toHaveValue('2028-02-13')
  await expiry.fill('2028-02-10')
  await page.getByLabel('规格', { exact: true }).fill('25kg')
  await expect(expiry).toHaveValue('2028-02-10')
})
