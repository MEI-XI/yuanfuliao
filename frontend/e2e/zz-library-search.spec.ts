import { expect, test } from '@playwright/test'

test('新增记录可搜索选择物料、方案和单个项目并带入内容', async ({ page }) => {
  if ((await (await page.request.get('/api/setup')).json()).required) await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出', exact: true })).toBeVisible()
  const suffix = Date.now()
  const ledger = await (await page.request.post('/api/ledgers', { data: { name: `搜索选择${suffix}` } })).json()
  const material = await (await page.request.post('/api/materials', { data: { name: `甘氨酸${suffix}`, model: 'AB123', aliases: '氨基乙酸', specification: '25kg' } })).json()
  const scheme = await (await page.request.post('/api/schemes', { data: { name: `食品标准${suffix}`, items: [{ name: '水分', standard: '≤0.2%' }] } })).json()
  await page.reload()
  await page.getByRole('button', { name: `进入${ledger.name}`, exact: true }).click()
  await page.getByRole('button', { name: '上传与录入', exact: true }).click()
  await page.getByRole('combobox', { name: '选择共享物料', exact: true }).fill('氨基乙酸 ab123')
  await page.getByRole('option', { name: `甘氨酸${suffix} AB123`, exact: true }).click()
  await expect(page.getByLabel('物料名称、型号', { exact: true })).toHaveValue(`甘氨酸${suffix} AB123`)
  await expect(page.getByLabel('规格', { exact: true })).toHaveValue('25kg')
  await page.getByRole('combobox', { name: '选择共享物料', exact: true }).click()
  await page.getByRole('combobox', { name: '选择共享物料', exact: true }).fill('没有匹配的选项')
  await expect(page.getByText('没有匹配结果，请修改搜索词。', { exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: '选择共享物料', exact: true }).press('Escape')
  await expect(page.getByLabel('物料名称、型号', { exact: true })).toHaveValue(`甘氨酸${suffix} AB123`)
  await page.getByRole('radio', { name: '检验', exact: true }).check()
  await page.getByRole('combobox', { name: '检验标准方案', exact: true }).fill('食品标准')
  await page.getByRole('option', { name: `食品标准${suffix}`, exact: true }).click()
  await expect(page.getByLabel('检验依据', { exact: true })).toHaveValue(`食品标准${suffix}`)
  await page.getByRole('combobox', { name: '已维护检验项目', exact: true }).fill('水分 0.2')
  await page.getByRole('option', { name: `食品标准${suffix} / 水分 / ≤0.2%`, exact: true }).click()
  await page.getByRole('button', { name: '添加选中项目', exact: true }).click()
  await expect(page.getByLabel('项目', { exact: true })).toHaveCount(2)
  await expect(page.getByLabel('标准规定', { exact: true }).last()).toHaveValue('≤0.2%')
})

test('管理方案可搜索绑定物料，长选项限制宽度并提供完整悬停文字', async ({ page }) => {
  if ((await (await page.request.get('/api/setup')).json()).required) await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出', exact: true })).toBeVisible()
  const name = `长名称物料${Date.now()}${'食品级原辅料'.repeat(8)}`
  const material = await (await page.request.post('/api/materials', { data: { name, aliases: '长选项测试别名' } })).json()
  await page.getByRole('button', { name: '管理与公共资料', exact: true }).click()
  await page.getByRole('button', { name: '检验标准方案', exact: true }).click()
  await page.getByRole('button', { name: '新增检验方案', exact: true }).click()
  const select = page.getByRole('combobox', { name: '方案所属物料', exact: true })
  await select.fill('长选项测试别名')
  const option = page.getByRole('option', { name, exact: true })
  await expect(option).toBeVisible()
  await expect(option).toHaveAttribute('title', name)
  const optionBox = await option.boundingBox()
  const controlBox = await page.locator('.searchable-library .el-select').boundingBox()
  expect(optionBox!.width).toBeLessThanOrEqual(controlBox!.width + 2)
  await option.click()
  await page.getByLabel('方案名称', { exact: true }).fill(`搜索绑定方案${material.id}`)
  await page.getByRole('button', { name: '创建检验方案', exact: true }).click()
  await expect(page.getByRole('region', { name: '新增检验方案', exact: true })).not.toBeVisible()
  const schemes = await (await page.request.get('/api/schemes')).json()
  expect(schemes.find((entry: { name: string }) => entry.name === `搜索绑定方案${material.id}`).material_id).toBe(material.id)
})
