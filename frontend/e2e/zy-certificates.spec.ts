import { test, expect } from '@playwright/test'

test('随车证件支持多选编辑并复用已保存的历史文字', async ({ page }) => {
  await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '新建公司台账' })).toBeVisible()
  expect((await page.request.post('/api/ledgers', { data: { name: '证件测试公司' } })).status()).toBe(201)
  await page.reload()
  await page.getByRole('button', { name: '进入证件测试公司' }).click()
  await page.getByRole('button', { name: '上传与录入' }).click()
  expect((await page.request.post('/api/materials', { data: { name: '快捷保存重名测试' } })).status()).toBe(201)
  await page.getByLabel('物料名称、型号', { exact: true }).fill('快捷保存重名测试')
  await page.getByRole('button', { name: '保存为物料信息', exact: true }).click()
  await page.getByRole('button', { name: '确认新增物料', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('重名')
  await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('checkbox', { name: '出厂检验报告', exact: true }).check()
  await page.getByRole('checkbox', { name: '检疫证', exact: true }).check()
  await expect(page.getByLabel('随车证件', { exact: true })).toHaveValue('出厂检验报告、检疫证')
  await page.getByLabel('随车证件', { exact: true }).fill('出厂检验报告、检疫证、自定义原产地证明')
  await page.getByRole('button', { name: '保存记录', exact: true }).click()
  await page.getByRole('button', { name: '上传与录入' }).click()
  await page.getByRole('checkbox', { name: '自定义原产地证明', exact: true }).check()
  await expect(page.getByLabel('随车证件', { exact: true })).toHaveValue('自定义原产地证明')
  await page.getByRole('checkbox', { name: '自定义原产地证明', exact: true }).uncheck()
  await expect(page.getByLabel('随车证件', { exact: true })).toHaveValue('')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('checkbox', { name: '肉品品质合格证', exact: true }).check()
  await expect(page.getByLabel('随车证件', { exact: true })).toHaveValue('肉品品质合格证')
  await page.locator('.certificate-picker').screenshot({ path: '../tmp/certificate-picker-mobile.png' })
})
