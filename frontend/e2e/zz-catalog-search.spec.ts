import { expect, test } from '@playwright/test'

test('物料与方案独立筛选，编辑返回保留条件', async ({ page }) => {
  if ((await (await page.request.get('/api/setup')).json()).required) await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出', exact: true })).toBeVisible()
  const suffix = Date.now()
  const material = await (await page.request.post('/api/materials', { data: { name: `搜索物料${suffix}`, model: 'AB123', company_name: '查找供应商' } })).json()
  const bound = `绑定标准${suffix}`, general = `通用标准${suffix}`
  await page.request.post('/api/schemes', { data: { name: bound, material_id: material.id, items: [{ name: '水分', standard: '≤0.2%' }] } })
  await page.request.post('/api/schemes', { data: { name: general, items: [{ name: '感官', standard: '无杂质' }] } })
  await page.getByRole('button', { name: '管理与公共资料', exact: true }).click()
  await expect(page.getByRole('button', { name: '新增检验方案', exact: true })).toHaveCount(0)
  await page.getByLabel('查找物料', { exact: true }).fill('ab123 查找供应商')
  await expect(page.locator('.maintenance-row')).toHaveCount(1)
  await expect(page.getByRole('columnheader', { name: '添加时间', exact: true })).toBeVisible()
  await page.getByLabel('物料开始日期', { exact: true }).fill('2099-01-01')
  await expect(page.locator('.maintenance-row')).toHaveCount(0)
  await page.getByLabel('物料开始日期', { exact: true }).fill('')
  await expect(page.locator('.maintenance-row')).toHaveCount(1)
  await page.getByRole('button', { name: '检验标准方案', exact: true }).click()
  await expect(page.getByRole('button', { name: '新增物料', exact: true })).toHaveCount(0)
  await page.getByLabel('查找检验方案', { exact: true }).fill('水分 0.2')
  await page.getByLabel('方案类型', { exact: true }).selectOption('bound')
  const row = page.locator('.maintenance-row').filter({ hasText: bound })
  await expect(row).toBeVisible()
  await page.getByLabel('方案时间类型', { exact: true }).selectOption('updated_at')
  await page.getByLabel('方案结束日期', { exact: true }).fill('2000-01-01')
  await expect(row).toHaveCount(0)
  await page.getByLabel('方案结束日期', { exact: true }).fill('')
  await expect(row).toBeVisible()
  await expect(page.locator('.maintenance-row').filter({ hasText: general })).toHaveCount(0)
  await row.getByRole('button', { name: /修改/ }).click()
  await expect(page.getByLabel('方案名称')).toHaveValue(bound)
  await page.getByRole('button', { name: '取消返回', exact: true }).click()
  await expect(page.getByLabel('查找检验方案', { exact: true })).toHaveValue('水分 0.2')
  await page.getByLabel('方案类型', { exact: true }).selectOption('general')
  await expect(page.getByText('没有匹配的方案，请调整或清空筛选。')).toBeVisible()
  await page.getByRole('button', { name: '清空筛选', exact: true }).click()
  await expect(page.locator('.maintenance-row').filter({ hasText: general })).toBeVisible()
  await page.getByRole('button', { name: '物料维护', exact: true }).click()
  await expect(page.getByLabel('查找物料', { exact: true })).toHaveValue('ab123 查找供应商')
  await page.getByLabel('查找物料', { exact: true }).fill('不存在的物料')
  await expect(page.getByText('没有匹配的物料，请调整或清空筛选。')).toBeVisible()
  await page.getByRole('button', { name: '清空筛选', exact: true }).click()
  await expect(page.locator('.maintenance-row').filter({ hasText: material.name })).toBeVisible()
  // A long list must return to the edited entry after both cancel and save.
  for (let index = 0; index < 25; index++) {
    await page.request.post('/api/schemes', { data: { name: `定位方案${suffix}-${index}`, items: [] } })
  }
  await page.reload()
  await page.getByRole('button', { name: '管理与公共资料', exact: true }).click()
  await page.getByRole('button', { name: '检验标准方案', exact: true }).click()
  const last = page.locator('.maintenance-row').filter({ hasText: `定位方案${suffix}-24` })
  await last.scrollIntoViewIfNeeded()
  await last.getByRole('button', { name: /修改/ }).click()
  await page.getByRole('button', { name: '返回列表', exact: true }).click()
  await expect(last).toBeInViewport()
  expect(await page.evaluate(() => window.scrollY)).toBeGreaterThan(300)
  await last.getByRole('button', { name: /修改/ }).click()
  await page.getByRole('button', { name: '保存修改', exact: true }).click()
  await expect(page.getByText('已保存', { exact: true })).toBeVisible()
  await expect(last).toBeInViewport()
  expect(await page.evaluate(() => window.scrollY)).toBeGreaterThan(300)
  await page.getByLabel('查找检验方案', { exact: true }).fill(`定位方案${suffix}`)
  await page.getByRole('button', { name: '全选筛选结果', exact: true }).click()
  await expect(page.getByText('已选 25 条', { exact: true })).toBeVisible()
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: '批量删除', exact: true }).click()
  await expect(page.locator('.maintenance-row')).toHaveCount(25)
  // Changing filters must not silently retain hidden selections.
  await page.getByLabel('查找检验方案', { exact: true }).fill(`定位方案${suffix}-24`)
  await expect(page.getByRole('button', { name: '批量删除', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '全选筛选结果', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '批量删除', exact: true }).click()
  await expect(last).toHaveCount(0)
  await page.getByRole('button', { name: '清空筛选', exact: true }).click()
  await expect(page.locator('.maintenance-row').filter({ hasText: bound })).toBeVisible()
  await page.getByRole('button', { name: '物料维护', exact: true }).click()
  await page.getByLabel('查找物料', { exact: true }).fill(material.name)
  await page.getByRole('button', { name: '全选筛选结果', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '批量删除', exact: true }).click()
  await expect(page.locator('.maintenance-row')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '批量删除', exact: true })).toBeDisabled()
  const updated = (await (await page.request.get('/api/schemes')).json()).find((entry: { name: string }) => entry.name === bound)
  expect(updated.material_id).toBeNull()
})
