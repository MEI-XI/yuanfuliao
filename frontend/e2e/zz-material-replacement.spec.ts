import { expect, test } from '@playwright/test'

test('管理维护和录入快捷保存共用同名替换规则，相同物料提示且不重复加入列表', async ({ page }) => {
  if ((await (await page.request.get('/api/setup')).json()).required) await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出', exact: true })).toBeVisible()
  const name = `同名替换${Date.now()}`
  const original = await (await page.request.post('/api/materials', { data: { name, specification: '25kg' } })).json()
  const ledger = await (await page.request.post('/api/ledgers', { data: { name } })).json()
  await page.getByRole('button', { name: '管理与公共资料', exact: true }).click()
  await page.getByRole('button', { name: '物料维护', exact: true }).click()
  await page.getByRole('button', { name: '新增物料', exact: true }).click()
  await page.getByLabel('物料名称', { exact: true }).fill(name)
  await page.getByLabel('规格', { exact: true }).fill('20kg')
  await page.getByRole('button', { name: '保存物料', exact: true }).click()
  await expect(page.getByText('已替换同名物料', { exact: true })).toBeVisible()
  const row = page.locator('.maintenance-row').filter({ hasText: name })
  await expect(row).toHaveCount(1)
  await row.getByRole('button', { name: '修改', exact: true }).click()
  await expect(page.getByLabel('规格', { exact: true })).toHaveValue('20kg')
  await page.getByRole('button', { name: '保存修改', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('已经有同样的物料')

  await page.reload()
  await page.getByRole('button', { name: `进入${ledger.name}`, exact: true }).click()
  await page.getByRole('button', { name: '上传与录入', exact: true }).click()
  const select = page.getByRole('combobox', { name: '选择共享物料', exact: true })
  await select.fill(name)
  await page.getByRole('option', { name, exact: true }).click()
  await expect(page.getByLabel('规格', { exact: true })).toHaveValue('20kg')
  await page.getByLabel('规格', { exact: true }).fill('30kg')
  await page.getByRole('button', { name: '保存为物料信息', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '保存为物料信息', exact: true })
  await dialog.getByRole('button', { name: '确认保存物料', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByText('已替换同名物料；本次查验记录仍需保存', { exact: true })).toBeVisible()
  await select.fill(name)
  await expect(page.getByRole('option', { name, exact: true })).toHaveCount(1)
  await page.getByRole('option', { name, exact: true }).click()
  await page.getByRole('button', { name: '保存为物料信息', exact: true }).click()
  await dialog.getByRole('button', { name: '确认保存物料', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('已经有同样的物料')
  const schemes = (await (await page.request.get('/api/materials')).json()).filter((entry: { name: string }) => entry.name === name)
  expect(schemes).toHaveLength(1)
  expect(schemes[0].id).toBe(original.id)
  expect(schemes[0].specification).toBe('30kg')
})
