import { expect, test, type Page } from '@playwright/test'

async function openMaintenance(page: Page) {
  const setup = await page.request.get('/api/setup')
  if ((await setup.json()).required) {
    await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  }
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('button', { name: '管理与公共资料', exact: true }).click()
}

test('管理员取消或确认删除公共资料，重新新增表单为空并保留旧记录', async ({ page }) => {
  await openMaintenance(page)
  const material = await (await page.request.post('/api/materials', { data: { name: '删除测试物料' } })).json()
  const scheme = await (await page.request.post('/api/schemes', { data: { material_id: material.id, name: '删除测试方案', items: [{ name: '水分', standard: '≤0.2%', unit: '%' }] } })).json()
  const partner = await (await page.request.post('/api/partners', { data: { name: '删除测试单位', kind: 'supplier' } })).json()
  const ledger = await (await page.request.post('/api/ledgers', { data: { name: '删除测试历史台账' } })).json()
  const record = await (await page.request.post(`/api/ledgers/${ledger.id}/records`, { data: { material_id: material.id, scheme_id: scheme.id, fields: { company_name: partner.name } } })).json()
  await page.reload()
  await page.getByRole('button', { name: '管理与公共资料', exact: true }).click()
  await expect(page.getByLabel('单位', { exact: true })).toHaveCount(0)
  const materialRow = page.locator('section').filter({ has: page.getByRole('heading', { name: '共享物料', exact: true }) }).locator('.maintenance-row').filter({ hasText: material.name })
  await materialRow.getByRole('button', { name: /修改/ }).click()
  await expect(page.getByLabel('物料名称', { exact: true })).toHaveValue(material.name)
  await page.getByRole('button', { name: '返回列表', exact: true }).click()
  page.once('dialog', async dialog => { expect(dialog.message()).toContain(material.name); await dialog.dismiss() })
  await materialRow.getByRole('button', { name: '删除', exact: true }).click()
  await expect(materialRow).toBeVisible()
  await materialRow.getByRole('button', { name: /修改/ }).click()
  await expect(page.getByLabel('物料名称', { exact: true })).toHaveValue(material.name)
  await page.getByRole('button', { name: '取消返回', exact: true }).click()
  page.once('dialog', async dialog => { expect(dialog.message()).toContain(material.name); await dialog.accept() })
  await materialRow.getByRole('button', { name: '删除', exact: true }).click()
  await expect(materialRow).toHaveCount(0)
  await page.getByRole('button', { name: '新增物料', exact: true }).click()
  await expect(page.getByLabel('物料名称', { exact: true })).toHaveValue('')
  await page.getByRole('button', { name: '取消返回', exact: true }).click()
  const schemeRow = page.locator('.maintenance-row').filter({ hasText: scheme.name })
  await schemeRow.getByRole('button', { name: /修改/ }).click()
  await page.getByRole('button', { name: '保存修改', exact: true }).click()
  await expect(page.getByLabel('方案名称')).toHaveCount(0)
  const savedScheme = (await (await page.request.get('/api/schemes')).json()).find((entry: { id: number }) => entry.id === scheme.id)
  expect(savedScheme.items[0].unit).toBe('')
  await schemeRow.getByRole('button', { name: /修改/ }).click()
  await expect(page.getByLabel('方案名称')).toHaveValue(scheme.name)
  await page.getByRole('button', { name: '返回列表', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await schemeRow.getByRole('button', { name: '删除', exact: true }).click()
  await expect(schemeRow).toHaveCount(0)
  await page.getByRole('button', { name: '新增检验方案', exact: true }).click()
  await expect(page.getByLabel('方案名称')).toHaveValue('')
  await page.getByRole('button', { name: '取消返回', exact: true }).click()
  await page.getByRole('button', { name: '单位资料', exact: true }).click()
  const partnerRow = page.locator('.maintenance-row').filter({ hasText: partner.name })
  await partnerRow.getByRole('button', { name: /修改/ }).click()
  await expect(page.getByLabel('单位名称')).toHaveValue(partner.name)
  await page.getByRole('button', { name: '返回列表', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await partnerRow.getByRole('button', { name: '删除', exact: true }).click()
  await expect(partnerRow).toHaveCount(0)
  await page.getByRole('button', { name: '新增单位', exact: true }).click()
  await expect(page.getByLabel('单位名称')).toHaveValue('')
  expect(await (await page.request.get(`/api/records/${record.id}`)).json()).toEqual({ ...record, material_id: null })
})

test('账号与台账可删除闲置条目，当前账号和有记录台账显示原因', async ({ page }) => {
  await openMaintenance(page)
  await page.request.post('/api/users', { data: { username: 'delete-unused-user', password: 'browser-test-password' } })
  await page.request.post('/api/ledgers', { data: { name: '删除测试空台账' } })
  const used = await (await page.request.post('/api/ledgers', { data: { name: '删除测试非空台账' } })).json()
  await page.request.post(`/api/ledgers/${used.id}/records`, { data: {} })
  await page.reload()
  await page.getByRole('button', { name: '管理与公共资料', exact: true }).click()
  await page.getByRole('button', { name: '账号与权限', exact: true }).click()
  page.on('dialog', dialog => dialog.accept())
  const accountRow = page.locator('.maintenance-row').filter({ hasText: 'delete-unused-user' })
  await accountRow.getByRole('button', { name: /修改/ }).click()
  await expect(page.getByLabel('人员账号')).toHaveValue('delete-unused-user')
  await page.getByRole('button', { name: '返回列表', exact: true }).click()
  await accountRow.getByRole('button', { name: '删除', exact: true }).click()
  await expect(accountRow).toHaveCount(0)
  await page.getByRole('button', { name: '新增账号', exact: true }).click()
  await expect(page.getByLabel('人员账号')).toHaveValue('')
  await page.getByRole('button', { name: '取消返回', exact: true }).click()
  await page.locator('.maintenance-row').filter({ hasText: 'admin' }).getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('当前登录账号')
  await page.getByRole('button', { name: '公司台账', exact: true }).click()
  const emptyRow = page.locator('.maintenance-row').filter({ hasText: '删除测试空台账' })
  await emptyRow.getByRole('button', { name: /修改/ }).click()
  await expect(page.getByLabel('台账名称', { exact: true })).toHaveValue('删除测试空台账')
  await page.getByRole('button', { name: '返回列表', exact: true }).click()
  await emptyRow.getByRole('button', { name: '删除', exact: true }).click()
  await expect(emptyRow).toHaveCount(0)
  await page.getByRole('button', { name: '新增台账', exact: true }).click()
  await expect(page.getByLabel('台账名称', { exact: true })).toHaveValue('')
  await page.getByRole('button', { name: '取消返回', exact: true }).click()
  const usedRow = page.locator('.maintenance-row').filter({ hasText: '删除测试非空台账' })
  await usedRow.getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('查验记录')
  await expect(usedRow).toBeVisible()
})
