import { test, expect, type Page } from '@playwright/test'

async function enter(page: Page) {
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('button', { name: '进入青山科技' }).click()
}

test('批量保存可勾选核对，方案名称带入依据且人工修改保留', async ({ page }) => {
  await enter(page)
  const first = await (await page.request.post('/api/schemes', { data: { name: '批量方案甲' } })).json()
  const second = await (await page.request.post('/api/schemes', { data: { name: '批量方案乙' } })).json()
  await page.getByRole('button', { name: '上传与录入' }).click()
  await page.getByRole('button', { name: '多种物料批量', exact: true }).click()
  await page.getByLabel('选择包装照片').setInputFiles(Array(2).fill('../tests/fixtures/label.png'))
  await page.getByLabel('物料名称、型号', { exact: true }).fill('批量保存甲')
  await page.getByRole('radio', { name: '检验', exact: true }).check()
  await page.getByLabel('检验标准方案', { exact: true }).selectOption(String(first.id))
  await expect(page.getByLabel('检验依据', { exact: true })).toHaveValue('批量方案甲')
  await page.getByLabel('检验依据', { exact: true }).fill('本次人工依据')
  await page.getByLabel('检验标准方案', { exact: true }).selectOption(String(second.id))
  await expect(page.getByLabel('检验依据', { exact: true })).toHaveValue('本次人工依据')
  await page.getByRole('button', { name: '记录 2 · 1 张', exact: true }).click()
  await page.getByLabel('物料名称、型号', { exact: true }).fill('批量保存乙')
  await page.getByRole('button', { name: '全选分组', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: '同时标记为已核对', exact: true })).not.toBeChecked()
  await page.getByRole('button', { name: '全选分组', exact: true }).click()
  await page.getByRole('button', { name: '保存所选 2 条记录', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: '批量保存甲' })).toContainText('待核对')
  await expect(page.getByRole('row').filter({ hasText: '批量保存乙' })).toContainText('待核对')
  await page.getByRole('row').filter({ hasText: '批量保存甲' }).getByRole('button', { name: '核对 / 编辑' }).click()
  await expect(page.getByLabel('检验依据', { exact: true })).toHaveValue('本次人工依据')
  await page.getByRole('button', { name: '返回台账', exact: true }).click()
  await page.getByRole('button', { name: '上传与录入' }).click()
  await page.getByRole('button', { name: '多种物料批量', exact: true }).click()
  await page.getByLabel('选择包装照片').setInputFiles(Array(2).fill('../tests/fixtures/label.png'))
  await page.getByLabel('物料名称、型号', { exact: true }).fill('批量核对甲')
  await page.getByRole('button', { name: '记录 2 · 1 张', exact: true }).click()
  await page.getByLabel('物料名称、型号', { exact: true }).fill('批量核对乙')
  await page.getByRole('button', { name: '全选分组', exact: true }).click()
  await page.getByRole('checkbox', { name: '同时标记为已核对', exact: true }).check()
  await page.getByRole('button', { name: '全选分组', exact: true }).click()
  await page.getByRole('button', { name: '保存所选 2 条记录', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: '批量核对甲' })).toContainText('已核对')
  await expect(page.getByRole('row').filter({ hasText: '批量核对乙' })).toContainText('已核对')
})

test('作废记录移到独立回收站，管理员还原后回到待核对台账', async ({ page }) => {
  await enter(page)
  await page.getByRole('button', { name: '上传与录入' }).click()
  await page.getByLabel('物料名称、型号', { exact: true }).fill('回收还原样本')
  await page.getByRole('button', { name: '保存并标记已核对' }).click()
  const row = page.getByRole('row').filter({ hasText: '回收还原样本' })
  await row.getByRole('button', { name: '核对 / 编辑' }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '作废记录', exact: true }).click()
  await expect(row).toHaveCount(0)
  await page.getByRole('button', { name: '回收站', exact: true }).click()
  await expect(page.getByRole('heading', { name: '回收站', exact: true })).toBeVisible()
  await expect(page.getByText('超过 30 天自动永久删除', { exact: false })).toBeVisible()
  await expect(row).toContainText('回收还原样本')
  await row.getByRole('button', { name: '还原', exact: true }).click()
  await expect(row).toHaveCount(0)
  await page.getByRole('button', { name: '返回台账', exact: true }).click()
  await expect(row).toContainText('待核对')
})

for (const failure of ['网络断开', '网关502']) test(`批量保存${failure}后重试原批次，不重复生成记录`, async ({ page }) => {
  await enter(page)
  await page.getByRole('button', { name: '上传与录入' }).click()
  await page.getByRole('button', { name: '多种物料批量', exact: true }).click()
  await page.getByLabel('选择包装照片').setInputFiles(Array(2).fill('../tests/fixtures/label.png'))
  await page.getByLabel('物料名称、型号', { exact: true }).fill(`批量${failure}甲`)
  await page.getByRole('button', { name: '记录 2 · 1 张', exact: true }).click()
  await page.getByLabel('物料名称、型号', { exact: true }).fill(`批量${failure}乙`)
  await page.getByRole('button', { name: '开始识别', exact: true }).click()
  await expect(page.getByText('云端建议名称', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '开始识别', exact: true })).toBeEnabled()
  let calls = 0
  const submissions: unknown[] = []
  await page.route('**/records/batch', async route => {
    submissions.push(route.request().postDataJSON())
    const response = await route.fetch()
    if (++calls === 1) {
      if (failure === '网络断开') await route.abort()
      else await route.fulfill({ status: 502, json: { detail: '网关暂时不可用' } })
    } else await route.fulfill({ response })
  })
  await page.getByRole('button', { name: '全选分组', exact: true }).click()
  await page.getByRole('button', { name: '保存所选 2 条记录', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('尚未确认')
  await expect(page.getByLabel('物料名称、型号', { exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '开始识别', exact: true })).toBeDisabled()
  await expect(page.locator('.suggestion').filter({ hasText: '云端建议名称' }).getByRole('button', { name: '填入', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '重试批量保存', exact: true }).click()
  await expect(page.getByRole('table')).toBeVisible()
  expect(submissions).toHaveLength(2)
  expect(submissions[1]).toEqual(submissions[0])
  await expect(page.getByRole('row').filter({ hasText: `批量${failure}甲` })).toHaveCount(1)
  await expect(page.getByRole('row').filter({ hasText: `批量${failure}乙` })).toHaveCount(1)
})
