import { expect, test } from '@playwright/test'

test('从最后一页删除日志回到有效页，顺序不乱且可清空', async ({ page }) => {
  if ((await (await page.request.get('/api/setup')).json()).required) await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出', exact: true })).toBeVisible()
  const ledger = await (await page.request.post('/api/ledgers', { data: { name: `日志分页${Date.now()}` } })).json()
  for (let i = 0; i < 51; i++) await page.request.post(`/api/ledgers/${ledger.id}/records`, { data: {} })
  const before = await (await page.request.get('/api/audit-logs?page_size=100')).json()
  expect(before.total).toBeGreaterThan(50)
  expect(before.total).toBeLessThanOrEqual(100)
  await page.getByRole('button', { name: '管理与公共资料', exact: true }).click()
  await page.getByRole('button', { name: '操作日志', exact: true }).click()
  await page.getByRole('spinbutton', { name: '目标页码' }).fill('2')
  await page.getByRole('spinbutton', { name: '目标页码' }).press('Enter')
  await expect(page.getByText('每页 50 条 · 第 2 / 2 页', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '全选本页日志', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '批量删除日志', exact: true }).click()
  await expect(page.getByText('每页 50 条 · 第 1 / 1 页', { exact: true })).toBeVisible()
  const labels = await page.locator('.audit-table tbody input').evaluateAll(inputs => inputs.map(input => input.getAttribute('aria-label')))
  expect(labels).toEqual(before.items.slice(0, 50).map((row: { id: number }) => `选择操作日志${row.id}`))
  await page.getByRole('button', { name: '全选本页日志', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '批量删除日志', exact: true }).click()
  await expect(page.getByText('筛选 0 条 · 已选 0 条本页日志', { exact: true })).toBeVisible()
  await expect(page.locator('.audit-table tbody tr')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '上一页', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '下一页', exact: true })).toBeDisabled()
})
