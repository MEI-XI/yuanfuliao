import { test, expect } from '@playwright/test'

test('未检验默认收起锁定，开启后默认今天，切回保留内容且禁止Word导出', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('button', { name: '进入青山科技' }).click()
  await page.getByRole('button', { name: '上传与录入' }).click()
  await expect(page.getByRole('radio', { name: '未检验', exact: true })).toBeChecked()
  await expect(page.getByLabel('检验日期', { exact: true })).toHaveCount(0)
  await page.getByLabel('物料名称、型号', { exact: true }).fill('检验开关测试')
  await page.getByRole('radio', { name: '检验', exact: true }).check()
  const today = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Shanghai', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date())
  await expect(page.getByLabel('检验日期', { exact: true })).toHaveValue(today)
  await expect(page.getByLabel('检验员', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('批准', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '添加检验项目', exact: true }).click()
  await expect(page.getByLabel('单位', { exact: true })).toHaveCount(0)
  await page.getByLabel('项目', { exact: true }).fill('外观')
  await page.getByLabel('检验结果', { exact: true }).fill('人工结果')
  await page.getByLabel('检验日期', { exact: true }).fill('2026-01-14')
  await page.getByRole('button', { name: '修改模板文件', exact: true }).click()
  await expect(page.getByRole('heading', { name: '我的模板', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '我的模板', exact: true }).click()
  await expect(page.getByRole('button', { name: '返回录入界面', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '返回录入界面', exact: true }).click()
  await expect(page.getByLabel('检验结果', { exact: true })).toHaveValue('人工结果')
  await page.getByRole('radio', { name: '未检验', exact: true }).check()
  await expect(page.getByLabel('检验日期', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '保存记录', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: '检验开关测试' })
  await expect(row).toContainText('未检验')
  await page.getByRole('button', { name: '清空选择', exact: true }).click()
  await row.getByRole('checkbox').check()
  let wordReminder = ''
  page.once('dialog', async dialog => { wordReminder = dialog.message(); await dialog.accept() })
  await page.getByRole('button', { name: '导出 Word', exact: true }).click()
  expect(wordReminder).toContain('取消勾选未检验记录')
  await row.getByRole('button', { name: '核对 / 编辑' }).click()
  await expect(page.getByRole('radio', { name: '未检验', exact: true })).toBeChecked()
  await page.getByRole('radio', { name: '检验', exact: true }).check()
  await expect(page.getByLabel('检验结果', { exact: true })).toHaveValue('人工结果')
  await expect(page.getByLabel('检验日期', { exact: true })).toHaveValue('2026-01-14')
  await page.getByLabel('检验结果', { exact: true }).fill('更新后保留')
  await page.getByRole('radio', { name: '未检验', exact: true }).check()
  await page.getByRole('button', { name: '保存记录', exact: true }).click()
  await expect(row).toContainText('未检验')
  await row.getByRole('button', { name: '核对 / 编辑' }).click()
  await page.getByRole('radio', { name: '检验', exact: true }).check()
  await expect(page.getByLabel('检验结果', { exact: true })).toHaveValue('更新后保留')
  await page.screenshot({ path: '../tmp/inspection-mode-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '../tmp/inspection-mode-mobile.png', fullPage: true })
  await page.getByRole('button', { name: '保存并标记已核对', exact: true }).click()
  await expect(row.getByRole('cell', { name: '检验', exact: true })).toBeVisible()
})
