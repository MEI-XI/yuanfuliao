import { expect, test, type Page } from '@playwright/test'

async function login(page: Page, username = 'admin', password = 'browser-test-password') {
  if ((await (await page.request.get('/api/setup')).json()).required) await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出', exact: true })).toBeVisible()
}

test('回收站批量还原和永久删除仅作用于勾选的筛选结果', async ({ page }) => {
  await login(page)
  const company = `批量回收${Date.now()}`
  const ledger = await (await page.request.post('/api/ledgers', { data: { name: company } })).json()
  for (const name of ['待还原甲', '待还原乙', '保留丙']) {
    const row = await (await page.request.post(`/api/ledgers/${ledger.id}/records`, { data: { fields: { material_name: name } } })).json()
    await page.request.post(`/api/records/${row.id}/void`, { data: { version: row.version } })
  }
  await page.reload()
  await page.getByRole('button', { name: `进入${company}` }).click()
  await page.getByRole('button', { name: '回收站', exact: true }).click()
  await expect(page.getByRole('button', { name: '批量还原', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '全选筛选结果', exact: true }).click()
  await page.getByLabel('查找回收记录').fill('待还原')
  await expect(page.getByText('已选 2 条', { exact: true })).toBeVisible()
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: '批量还原', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(2)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '批量还原', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(0)
  await page.getByRole('button', { name: '清空筛选', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await expect(page.locator('tbody tr')).toContainText('保留丙')
  await page.getByRole('button', { name: '全选筛选结果', exact: true }).click()
  await page.getByRole('button', { name: '清空选择', exact: true }).click()
  await expect(page.getByRole('button', { name: '批量永久删除', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '全选筛选结果', exact: true }).click()
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: '批量永久删除', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '批量永久删除', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(0)
  await page.getByRole('button', { name: '返回台账', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(2)
  await expect(page.locator('tbody tr').first()).toContainText('待核对')
})

test('日志上方提示30天清理，批量删除只删除勾选日志且筛选后清空选择', async ({ page }) => {
  await login(page)
  const ledger = await (await page.request.post('/api/ledgers', { data: { name: `日志批删${Date.now()}` } })).json()
  for (let i = 0; i < 3; i++) await page.request.post(`/api/ledgers/${ledger.id}/records`, { data: {} })
  await page.getByRole('button', { name: '管理与公共资料', exact: true }).click()
  await page.getByRole('button', { name: '操作日志', exact: true }).click()
  await expect(page.getByRole('note', { name: '操作日志保留期限' })).toContainText('超过 30 天自动永久删除')
  await page.getByLabel('日志操作对象').fill(`/api/ledgers/${ledger.id}/records`)
  await page.getByRole('button', { name: '筛选日志', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(3)
  await expect(page.locator('tbody tr').first()).toContainText(`创建记录：${ledger.name}台账`)
  await page.locator('tbody tr').first().getByRole('button', { name: '查看详情', exact: true }).click()
  const details = page.getByRole('dialog', { name: '操作日志详情', exact: true })
  await expect(details).toContainText(`创建记录：${ledger.name}台账`)
  await details.getByRole('button', { name: '关闭详情', exact: true }).click()
  await expect(details).not.toBeVisible()
  await page.getByRole('button', { name: '全选本页日志', exact: true }).click()
  await page.getByRole('button', { name: '筛选日志', exact: true }).click()
  await expect(page.getByRole('button', { name: '批量删除日志', exact: true })).toBeDisabled()
  await page.locator('tbody tr').nth(0).getByRole('checkbox').check()
  await page.locator('tbody tr').nth(1).getByRole('checkbox').check()
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: '批量删除日志', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(3)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '批量删除日志', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await expect(page.getByRole('status').filter({ hasText: '已删除 2 条操作日志' })).toBeVisible()
  await page.getByRole('button', { name: '全选本页日志', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '批量删除日志', exact: true }).click()
  await expect(page.getByText('筛选 0 条 · 已选 0 条本页日志', { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '../tmp/audit-retention-mobile.png', fullPage: true })
})

test('普通用户没有回收站批量操作，管理员有回收站操作但没有日志管理', async ({ page }) => {
  await login(page)
  await page.request.post('/api/users', { data: { username: 'bulk-worker', password: 'worker-password' } })
  await page.request.post('/api/users', { data: { username: 'bulk-manager', password: 'manager-password', role: 'admin' } })
  await page.getByRole('button', { name: '退出', exact: true }).click()
  await login(page, 'bulk-worker', 'worker-password')
  await page.getByRole('button', { name: '回收站', exact: true }).click()
  await expect(page.getByRole('heading', { name: '回收站', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '批量还原', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '批量永久删除', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '退出', exact: true }).click()
  await login(page, 'bulk-manager', 'manager-password')
  await page.getByRole('button', { name: '回收站', exact: true }).click()
  await expect(page.getByRole('button', { name: '批量还原', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '批量永久删除', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '管理与公共资料', exact: true }).click()
  await expect(page.getByRole('button', { name: '操作日志', exact: true })).toHaveCount(0)
})
