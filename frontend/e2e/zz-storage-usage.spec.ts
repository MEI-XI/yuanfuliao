import { expect, test } from '@playwright/test'

test('管理员可查看空间分类并刷新，手机显示和失败重试正常', async ({ page }) => {
  test.setTimeout(60000)
  if ((await (await page.request.get('/api/setup')).json()).required) await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '管理与公共资料', exact: true }).click()
  await page.getByRole('button', { name: '占用空间', exact: true }).click()
  const section = page.getByRole('region', { name: '占用空间明细', exact: true })
  await expect(section.getByText('必要运行与业务数据占用', { exact: true })).toBeVisible({ timeout: 30000 })
  await expect(section.getByText('业务文件所在磁盘剩余', { exact: true })).toBeVisible()
  await expect(section.getByRole('cell', { name: '业务数据库', exact: true })).toBeVisible()
  await expect(section.getByRole('heading', { name: '资源回收与保留规则', exact: true })).toBeVisible()
  await page.route('**/api/storage-usage', route => route.fulfill({ status: 503, json: { detail: '暂时无法读取空间信息' } }), { times: 1 })
  await section.getByRole('button', { name: '刷新统计', exact: true }).click()
  await expect(section.getByRole('alert')).toContainText('暂时无法读取空间信息')
  await expect(section.getByText('（上次成功结果）', { exact: true })).toBeVisible()
  await section.getByRole('button', { name: '重试统计', exact: true }).click()
  await expect(section.getByRole('alert')).toHaveCount(0)
  await expect(section.getByRole('button', { name: '刷新统计', exact: true })).toBeEnabled({ timeout: 30000 })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await section.screenshot({ path: '../tmp/storage-usage-mobile.png' })
})
