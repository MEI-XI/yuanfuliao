  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('button', { name: '进入青山科技' }).click()
  await page.getByRole('button', { name: '上传与录入' }).click()
  await page.getByRole('button', { name: '多种物料批量', exact: true }).click()
  await page.getByLabel('选择包装照片').setInputFiles(['../tests/fixtures/label.png', '../tests/fixtures/label.png'])
  await page.getByLabel('云端辅助', { exact: true }).uncheck()
  let submissions = 0
  let failedId = ''
  await page.getByRole('button', { name: '记录 2 · 1 张', exact: true }).click()
  const imageUrl = await page.locator('.thumbnail img').getAttribute('src')
  const targetImage = Number(imageUrl?.split('/').at(-1))
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/recognition')) submissions++ })
  await page.route('**/ledgers/*/recognition', async route => {
    const response = await route.fetch()
    await route.fulfill({ response, json: { ...await response.json(), local_status: 'done' } })
  })
  await page.route('**/api/recognition/*', async route => {
    const response = await route.fetch()
    const job = await response.json()
    if (job.image_ids.includes(targetImage) && !failedId) { failedId = route.request().url(); await route.abort(); return }
    await route.fulfill({ response })
  })
  await page.getByRole('button', { name: '开始识别', exact: true }).click()
  await page.getByRole('button', { name: '记录 2 · 1 张', exact: true }).click()
  await expect(page.getByRole('region', { name: '识别操作与进度' })).toContainText('状态更新中断')
  await expect(page.getByRole('button', { name: '重试获取状态', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '重试获取状态', exact: true }).click()
