test('移除图片后迟到的识别响应失效，空云端结果不生成填空建议', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('button', { name: '进入青山科技' }).click()
  await page.getByRole('button', { name: '上传与录入' }).click()
  await page.getByLabel('选择包装照片').setInputFiles('../tests/fixtures/label.png')
  let release = () => {}
  const held = new Promise<void>(resolve => { release = resolve })
  let arrived = () => {}
  const started = new Promise<void>(resolve => { arrived = resolve })
  await page.route('**/api/recognition/*', async route => {
    const response = await route.fetch()
    arrived(); await held
    await route.fulfill({ response })
  })
  await page.getByRole('button', { name: '开始识别', exact: true }).click()
  await started
  await expect(page.getByRole('heading', { name: '云端建议', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '移除', exact: true }).click()
  release()
  await page.waitForTimeout(800)
  await expect(page.getByLabel('物料名称、型号', { exact: true })).toHaveValue('')
  await expect(page.getByText('本地识别：', { exact: false })).toHaveCount(0)
})

test('补图可以直接保存，识别原文加载中保存不丢失关联', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('button', { name: '进入青山科技' }).click()
  await page.getByRole('button', { name: '上传与录入' }).click()
  await page.getByLabel('选择包装照片').setInputFiles('../tests/fixtures/label.png')
  await page.getByRole('button', { name: '开始识别', exact: true }).click()
  await expect(page.getByText('原始识别文字', { exact: true })).toBeVisible()
  await page.getByLabel('选择包装照片').setInputFiles('../tests/fixtures/label.png')
  await expect(page.getByLabel('当前图片分组')).toContainText('2 张')
  await page.getByRole('button', { name: '保存记录', exact: true }).click()
  await expect(page.getByRole('table')).toBeVisible()
  await page.getByRole('button', { name: '核对 / 编辑' }).first().click()
  await page.getByRole('button', { name: '开始识别', exact: true }).click()
  await expect(page.getByText('云端建议名称', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '保存记录', exact: true }).click()
  let release = () => {}
  const held = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/recognition/*', async route => { await held; await route.continue() })
  await page.getByRole('button', { name: '核对 / 编辑' }).first().click()
  const saving = page.waitForResponse(r => r.url().includes('/api/records/') && r.request().method() === 'PATCH')
  await page.getByRole('button', { name: '保存记录', exact: true }).click()
  const saved: unknown = await (await saving).json()
  release()
  expect(saved).toHaveProperty('recognition_job_id', expect.any(Number))
})
