import { expect, test } from '@playwright/test'

test('台账每页50条，支持跳页、跨页选择与筛选重置', async ({ page }) => {
  if ((await (await page.request.get('/api/setup')).json()).required) await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出', exact: true })).toBeVisible()
  const ledger = await (await page.request.post('/api/ledgers', { data: { name: `分页测试${Date.now()}` } })).json()
  for (let i = 1; i <= 51; i++) {
    const response = await page.request.post(`/api/ledgers/${ledger.id}/records`, { data: { fields: { material_name: `分页物料${String(i).padStart(2, '0')}` } } })
    expect(response.ok()).toBeTruthy()
  }
  await page.reload()
  await page.getByRole('button', { name: `进入${ledger.name}`, exact: true }).click()
  const rows = page.locator('.ledger-table tbody tr')
  await expect(rows).toHaveCount(50)
  await page.getByRole('button', { name: '按物料名称、型号排序', exact: true }).click()
  await rows.first().getByRole('checkbox').check()
  const pager = page.getByRole('navigation', { name: '台账分页', exact: true })
  await pager.getByRole('spinbutton', { name: '目标页码' }).fill('2')
  await pager.getByRole('button', { name: '跳转', exact: true }).click()
  await expect(rows).toHaveCount(1)
  await expect(rows.first()).toContainText('分页物料51')
  await rows.first().getByRole('checkbox').check()
  await expect(page.locator('.table-actions')).toContainText('已选 2 条')
  await pager.getByRole('spinbutton', { name: '目标页码' }).fill('99')
  await pager.getByRole('spinbutton', { name: '目标页码' }).press('Enter')
  await expect(pager).toContainText('第 2 / 2 页')
  await pager.getByRole('spinbutton', { name: '目标页码' }).fill('1')
  await pager.getByRole('spinbutton', { name: '目标页码' }).press('Enter')
  await expect(rows).toHaveCount(50)
  await expect(rows.first().getByRole('checkbox')).toBeChecked()
  await pager.getByRole('button', { name: '下一页', exact: true }).click()
  await page.getByLabel('查找记录', { exact: true }).fill('分页物料01')
  await expect(rows).toHaveCount(1)
  await expect(pager).toContainText('第 1 / 1 页')
  await page.getByLabel('查找记录', { exact: true }).fill('不存在的物料')
  await expect(rows).toHaveCount(0)
  await expect(pager.getByRole('button', { name: '下一页', exact: true })).toBeDisabled()
})
