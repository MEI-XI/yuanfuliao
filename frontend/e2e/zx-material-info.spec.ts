import { expect, test } from '@playwright/test'

test('公共物料补齐资料，选择后可改，核对后另存为新物料', async ({ page }) => {
  const setup = await page.request.get('/api/setup')
  if ((await setup.json()).required) await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出', exact: true })).toBeVisible()
  const name = `物料资料${Date.now()}`
  const ledger = await (await page.request.post('/api/ledgers', { data: { name } })).json()
  await page.getByRole('button', { name: '管理与公共资料', exact: true }).click()
  await page.getByRole('button', { name: '新增物料', exact: true }).click()
  await page.getByLabel('物料名称', { exact: true }).fill(name)
  await page.getByLabel('型号', { exact: true }).fill('M1')
  await page.getByLabel('规格', { exact: true }).fill('25kg/袋')
  await page.getByLabel('供应商或生产商', { exact: true }).fill('资料供应商')
  await page.getByLabel('地址', { exact: true }).fill('资料地址')
  await page.getByLabel('联系方式', { exact: true }).fill('123456')
  await page.getByLabel('保质期', { exact: true }).fill('12个月')
  await page.getByRole('combobox', { name: '地址来源', exact: true }).selectOption('supplier')
  await page.getByRole('button', { name: '创建物料', exact: true }).click()
  await page.locator('.maintenance-row').filter({ hasText: name }).getByRole('button', { name: /修改/ }).click()
  await expect(page.getByLabel('规格', { exact: true })).toHaveValue('25kg/袋')
  await expect(page.getByLabel('供应商或生产商', { exact: true })).toHaveValue('资料供应商')
  await expect(page.getByLabel('联系方式', { exact: true })).toHaveValue('123456')
  await page.getByRole('button', { name: '返回列表', exact: true }).click()
  await page.getByRole('button', { name: '新增物料', exact: true }).click()
  await expect(page.getByLabel('规格', { exact: true })).toHaveValue('')
  await expect(page.getByRole('combobox', { name: '地址来源', exact: true })).toHaveValue('')
  await page.getByRole('button', { name: '取消返回', exact: true }).click()
  await page.getByRole('button', { name: '返回公司台账', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: `进入${ledger.name}` }).click()
  await page.getByRole('button', { name: '上传与录入', exact: true }).click()
  await page.getByLabel('选择共享物料').selectOption({ label: `${name} M1` })
  await expect(page.getByLabel('规格', { exact: true })).toHaveValue('25kg/袋')
  await expect(page.getByRole('combobox', { name: '地址来源', exact: true })).toHaveValue('supplier')
  await page.getByLabel('规格', { exact: true }).fill('50kg/袋')
  await page.getByRole('button', { name: '保存为物料信息', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '保存为物料信息' })
  await expect(dialog.getByLabel('物料名称', { exact: true })).toHaveValue(name)
  await expect(dialog.getByLabel('型号', { exact: true })).toHaveValue('M1')
  await page.screenshot({ path: '../tmp/material-info-review.png', fullPage: true })
  await dialog.getByLabel('物料名称', { exact: true }).fill(name + '另存')
  await dialog.getByRole('button', { name: '确认新增物料', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  const materials = await (await page.request.get('/api/materials')).json()
  expect(materials.find((entry: { name: string }) => entry.name === name).specification).toBe('25kg/袋')
  expect(materials.find((entry: { name: string }) => entry.name === name + '另存').specification).toBe('50kg/袋')
})


test('已保存且未手改字段和共享资料不被重新识别覆盖，空白可补齐并可手动采用', async ({ page }) => {
  const setup = await page.request.get('/api/setup')
  if ((await setup.json()).required) await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出', exact: true })).toBeVisible()
  const name = `识别保留${Date.now()}`
  const ledger = await (await page.request.post('/api/ledgers', { data: { name } })).json()
  const material = await (await page.request.post('/api/materials', { data: { name: name + '共享', specification: '共享规格', company_name: '共享供应商', address: '共享地址', address_source: 'supplier', contact: '共享电话', contact_source: 'supplier' } })).json()
  await page.request.post(`/api/ledgers/${ledger.id}/records`, { data: { fields: { material_name: name, specification: '原规格', company_name: '原供应商', address: '原地址', address_source: 'supplier', contact: '原电话', contact_source: 'supplier', production_dates: ['2026-01-01'] } } })
  const suggestions = { material_name: '识别名称', specification: '识别规格', company_name: '识别供应商', address: '识别地址', address_source: 'manufacturer', contact: '识别电话', contact_source: 'manufacturer', shelf_life: '识别保质期', production_dates: ['2026-02-01'] }
  await page.route('**/api/recognition/*', async route => {
    const response = await route.fetch()
    const job = await response.json()
    await route.fulfill({ response, json: { ...job, local_status: 'done', cloud_status: 'done', fields: suggestions, cloud_fields: { company_name: '云端供应商' }, conflicts: {}, review_suggestions: { fields: { company_name: '历史供应商' }, conflicts: {}, sources: [] } } })
  })
  await page.reload()
  await page.getByRole('button', { name: `进入${name}` }).click()
  await page.getByRole('button', { name: '核对 / 编辑', exact: true }).click()
  await page.getByLabel('选择包装照片').setInputFiles('../tests/fixtures/label.png')
  await page.getByRole('button', { name: '开始识别', exact: true }).click()
  await expect(page.getByLabel('保质期', { exact: true })).toHaveValue('识别保质期')
  await expect(page.getByLabel('物料名称、型号', { exact: true })).toHaveValue(name)
  await expect(page.getByLabel('规格', { exact: true })).toHaveValue('原规格')
  await expect(page.getByLabel('供应商或生产商', { exact: true })).toHaveValue('原供应商')
  await expect(page.getByLabel('地址', { exact: true })).toHaveValue('原地址')
  await expect(page.getByRole('combobox', { name: '地址来源', exact: true })).toHaveValue('supplier')
  await expect(page.getByLabel('联系方式', { exact: true })).toHaveValue('原电话')
  await expect(page.getByLabel('联系方式来源', { exact: true })).toHaveValue('supplier')
  await expect(page.getByLabel('生产日期', { exact: true })).toHaveValue('2026.01.01')
  await page.getByLabel('选择共享物料').selectOption(String(material.id))
  await expect(page.getByLabel('规格', { exact: true })).toHaveValue('共享规格')
  await expect(page.getByLabel('保质期', { exact: true })).toHaveValue('识别保质期')
  const refreshed = page.waitForResponse(response => /\/api\/recognition\/\d+$/.test(response.url()))
  await page.getByRole('button', { name: '开始识别', exact: true }).click()
  await refreshed
  await expect(page.getByRole('button', { name: '开始识别', exact: true })).toBeEnabled()
  await expect(page.getByLabel('规格', { exact: true })).toHaveValue('共享规格')
  await expect(page.getByRole('combobox', { name: '地址来源', exact: true })).toHaveValue('supplier')
  await page.getByText('本地字段建议', { exact: true }).click()
  await page.locator('.suggestion').filter({ hasText: '识别规格' }).getByRole('button', { name: '填入', exact: true }).click()
  await expect(page.getByLabel('规格', { exact: true })).toHaveValue('识别规格')
  await page.locator('.suggestion').filter({ hasText: '云端供应商' }).getByRole('button', { name: '填入', exact: true }).click()
  await expect(page.getByLabel('供应商或生产商', { exact: true })).toHaveValue('云端供应商')
})

test('普通账号可选用和编辑物料资料，但没有保存共享物料按钮', async ({ page }) => {
  const setup = await page.request.get('/api/setup')
  if ((await setup.json()).required) await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  await page.request.post('/api/login', { data: { username: 'admin', password: 'browser-test-password' } })
  const name = `普通物料${Date.now()}`
  await (await page.request.post('/api/users', { data: { username: name, password: 'browser-test-password', role: 'user' } })).json()
  const ledger = await (await page.request.post('/api/ledgers', { data: { name } })).json()
  const material = await (await page.request.post('/api/materials', { data: { name, specification: '共享规格' } })).json()
  await page.request.post('/api/logout')
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill(name)
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出', exact: true })).toBeVisible()
  await page.getByRole('button', { name: `进入${name}` }).click()
  await page.getByRole('button', { name: '上传与录入', exact: true }).click()
  await page.getByLabel('选择共享物料').selectOption(String(material.id))
  await expect(page.getByLabel('规格', { exact: true })).toHaveValue('共享规格')
  await page.getByLabel('规格', { exact: true }).fill('普通用户编辑')
  await expect(page.getByRole('button', { name: '保存为物料信息', exact: true })).toHaveCount(0)
})

