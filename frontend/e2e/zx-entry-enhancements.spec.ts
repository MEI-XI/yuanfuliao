import { expect, test, type Page } from '@playwright/test'

async function login(page: Page) {
  const setup = await page.request.get('/api/setup')
  if ((await setup.json()).required) await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出', exact: true })).toBeVisible()
}

async function newEntry(page: Page, name: string) {
  await page.request.post('/api/ledgers', { data: { name } })
  await page.reload()
  await page.getByRole('button', { name: `进入${name}` }).click()
  await page.getByRole('button', { name: '上传与录入', exact: true }).click()
}

