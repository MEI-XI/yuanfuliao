import { expect, test } from '@playwright/test'

test('回收站每页50条，跳页保留勾选，批量还原和删除后回到有效页', async ({ page }) => {
  if ((await (await page.request.get('/api/setup')).json()).required) await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出', exact: true })).toBeVisible()
  const ledger = await (await page.request.post('/api/ledgers', { data: { name: `回收分页${Date.now()}` } })).json()
  const records: { id: number; version: number }[] = []
  for (let i = 1; i <= 52; i++) {
    const response = await page.request.post(`/api/ledgers/${ledger.id}/records`, { data: { fields: { material_name: `回收物料${i}` } } })
    expect(response.ok()).toBeTruthy()
    const record = await response.json()
    records.push({ id: record.id, version: record.version })
  }
  expect((await page.request.post('/api/records/batch-void', { data: { records } })).ok()).toBeTruthy()
  await page.reload()
  await page.getByRole('button', { name: `进入${ledger.name}`, exact: true }).click()
  await page.getByRole('button', { name: '回收站', exact: true }).click()
  const rows = page.locator('.recycle-panel tbody tr')
  await expect(rows).toHaveCount(50)
  const pager = page.getByRole('navigation', { name: '回收站分页', exact: true })
  await rows.first().getByRole('checkbox').check()
  await pager.getByRole('spinbutton', { name: '目标页码' }).fill('2')
  await pager.getByRole('spinbutton', { name: '目标页码' }).press('Enter')
  await expect(rows).toHaveCount(2)
  await rows.first().getByRole('checkbox').check()
  await expect(page.locator('.table-actions')).toContainText('已选 2 条')
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '批量还原', exact: true }).click()
  await expect(pager).toContainText('第 1 / 1 页')
  await expect(rows).toHaveCount(50)
  await page.getByLabel('查找回收记录', { exact: true }).fill('没有此物料')
  await expect(rows).toHaveCount(0)
  await expect(pager.getByRole('button', { name: '下一页', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '清空筛选', exact: true }).click()
  await page.getByRole('button', { name: '全选筛选结果', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '批量永久删除', exact: true }).click()
  await expect(rows).toHaveCount(0)
  await expect(pager).toContainText('第 1 / 1 页')
})
