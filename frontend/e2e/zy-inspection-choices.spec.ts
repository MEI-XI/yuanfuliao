import { test, expect } from '@playwright/test'

test('检验结果和判定结论单选、自由输入、记忆和删除', async ({ page }) => {
  await page.request.post('/api/setup', { data: { username: 'admin', password: 'browser-test-password' } })
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '新建公司台账' })).toBeVisible()
  await page.request.post('/api/ledgers', { data: { name: '检验选项测试公司' } })
  await page.reload()
  await page.getByRole('button', { name: '进入检验选项测试公司' }).click()
  await page.getByRole('button', { name: '上传与录入' }).click()
  await page.getByRole('radio', { name: '检验', exact: true }).check()
  await page.getByRole('button', { name: '添加检验项目', exact: true }).click()
  const row = page.locator('.inspection-row').first()
  await row.getByLabel('检验结果', { exact: true }).fill('0.2%')
  await row.getByLabel('判定结论', { exact: true }).click()
  await expect.poll(async () => (await page.request.get('/api/inspection-options/result')).json()).toContain('0.2%')
  await row.getByRole('option', { name: '合格', exact: true }).click()
  await expect(row.getByLabel('判定结论', { exact: true })).toHaveValue('合格')
  await row.getByLabel('检验结果', { exact: true }).click()
  await page.screenshot({ path: '../tmp/inspection-choice-desktop.png' })
  await row.getByRole('option', { name: '不符合', exact: true }).click()
  await expect(row.getByLabel('检验结果', { exact: true })).toHaveValue('不符合')
  await row.getByLabel('检验结果', { exact: true }).click()
  await row.getByRole('option', { name: '0.2%', exact: true }).click()
  await row.getByLabel('检验结果', { exact: true }).click()
  await row.getByRole('button', { name: '删除检验结果历史选项：0.2%' }).click()
  await expect(row.getByRole('option', { name: '0.2%', exact: true })).toHaveCount(0)
  await expect(row.getByLabel('检验结果', { exact: true })).toHaveValue('0.2%')
  await row.getByLabel('检验结果', { exact: true }).fill('')
  await row.getByLabel('检验结果', { exact: true }).fill('0.2%')
  await row.getByLabel('判定结论', { exact: true }).click()
  await expect.poll(async () => (await page.request.get('/api/inspection-options/result')).json()).toContain('0.2%')
  await page.setViewportSize({ width: 390, height: 844 })
  await row.getByLabel('检验结果', { exact: true }).click()
  await row.getByRole('option', { name: '符合', exact: true }).click()
  await expect(row.getByLabel('检验结果', { exact: true })).toHaveValue('符合')
  await row.scrollIntoViewIfNeeded()
  await row.getByLabel('检验结果', { exact: true }).click()
  await page.screenshot({ path: '../tmp/inspection-choice-mobile.png' })
  await page.getByRole('button', { name: '保存记录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '原辅料查验记录', exact: true })).toBeVisible()
})
